/**
 * sync-catalog.js
 *
 * Fetches the full published game catalog from the PlayBound site API and
 * writes it to catalog.js so the bundled launcher has an up-to-date offline
 * fallback. Run automatically before `npm run dist` via the predist hook.
 *
 * Usage:  node scripts/sync-catalog.js [--api-base https://playbound.club]
 */

const fs = require("fs");
const path = require("path");

const DEFAULT_API_BASE = "https://playbound.club";

async function main() {
  const args = process.argv.slice(2);
  const baseIdx = args.indexOf("--api-base");
  const apiBase = baseIdx !== -1 && args[baseIdx + 1] ? args[baseIdx + 1] : DEFAULT_API_BASE;
  const url = `${apiBase}/api/launcher/catalog`;

  console.log(`[sync-catalog] Fetching ${url} …`);

  const res = await fetch(url, {
    headers: { "user-agent": "playbound-sync-catalog", accept: "application/json" },
  });
  if (!res.ok) {
    throw new Error(`HTTP ${res.status} from ${url}`);
  }
  const data = await res.json();
  const games = Array.isArray(data.games) ? data.games : [];
  if (games.length === 0) {
    throw new Error("API returned 0 games — refusing to overwrite catalog.js with an empty list");
  }

  const catalogPath = path.join(__dirname, "..", "catalog.js");
  let merged = games;
  try {
    if (fs.existsSync(catalogPath)) {
      delete require.cache[require.resolve(catalogPath)];
      const existing = require(catalogPath);
      if (Array.isArray(existing)) {
        const bySlug = new Map(existing.map((g) => [g.slug, g]));
        for (const g of games) {
          bySlug.set(g.slug, g);
        }
        merged = Array.from(bySlug.values());
      }
    }
  } catch {
    merged = games;
  }

  const header = [
    "// Auto-generated by scripts/sync-catalog.js — do not edit by hand.",
    `// Synced from ${apiBase} at ${new Date().toISOString()}`,
    `// ${merged.length} game(s)`,
    "",
    "module.exports = ",
  ].join("\n");

  const json = JSON.stringify(merged, null, 2);
  fs.writeFileSync(catalogPath, header + json + ";\n", "utf-8");

  console.log(`[sync-catalog] Wrote ${merged.length} game(s) to catalog.js`);
}

main().catch((err) => {
  console.error(`[sync-catalog] ERROR: ${err.message}`);
  console.error("[sync-catalog] Build will continue with the existing catalog.js");
  // Exit 0 so the build isn't blocked if the site is unreachable
  process.exit(0);
});
