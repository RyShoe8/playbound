/**
 * sync-catalog.js
 *
 * Fetches the full published game catalog from the PlayBound site API and
 * writes it to catalog.js so the bundled launcher has an up-to-date offline
 * fallback. Run automatically before `npm run dist` via the predist hook.
 *
 * Usage:  node scripts/sync-catalog.js [--api-base https://playbound.club]
 */

const fs = require("fs");
const path = require("path");

const DEFAULT_API_BASE = process.env.PLAYBOUND_API_BASE || "http://localhost:3000";

async function main() {
  const args = process.argv.slice(2);
  const baseIdx = args.indexOf("--api-base");
  let apiBase = baseIdx !== -1 && args[baseIdx + 1] ? args[baseIdx + 1] : DEFAULT_API_BASE;
  let url = `${apiBase}/api/launcher/catalog?_t=${Date.now()}`;

  console.log(`[sync-catalog] Fetching ${url} …`);

  try {
    let res = await fetch(url, {
      cache: "no-store",
      headers: { "user-agent": "playbound-sync-catalog", accept: "application/json", "cache-control": "no-cache" },
    }).catch(() => null);

    if (!res || !res.ok) {
      if (apiBase !== "https://playbound.club") {
        apiBase = "https://playbound.club";
        url = `${apiBase}/api/launcher/catalog?_t=${Date.now()}`;
        console.log(`[sync-catalog] Local fetch failed, trying ${url} …`);
        res = await fetch(url, {
          cache: "no-store",
          headers: { "user-agent": "playbound-sync-catalog", accept: "application/json", "cache-control": "no-cache" },
        });
      }
    }
    if (!res || !res.ok) {
      throw new Error(`HTTP ${res?.status || "error"} from ${url}`);
    }
    const data = await res.json();
    const games = Array.isArray(data.games) ? data.games : [];
    if (games.length === 0) {
      throw new Error("API returned 0 games — refusing to overwrite catalog.js with an empty list");
    }

    const catalogPath = path.join(__dirname, "..", "catalog.js");
    const previousCount = (() => {
      try {
        if (!fs.existsSync(catalogPath)) return 0;
        delete require.cache[require.resolve(catalogPath)];
        const existing = require(catalogPath);
        return Array.isArray(existing) ? existing.length : 0;
      } catch {
        return 0;
      }
    })();

    const header = [
      "// Auto-generated by scripts/sync-catalog.js — do not edit by hand.",
      `// Synced from ${apiBase} at ${new Date().toISOString()}`,
      `// ${games.length} game(s)`,
      "",
      "module.exports = ",
    ].join("\n");

    const json = JSON.stringify(games, null, 2);
    fs.writeFileSync(catalogPath, header + json + ";\n", "utf-8");

    const delta = games.length - previousCount;
    const note = delta === 0 ? "" : ` (${delta > 0 ? "+" : ""}${delta} vs previous ${previousCount})`;
    console.log(`[sync-catalog] Wrote ${games.length} game(s) to catalog.js${note}`);

    writeVocabulary(data, apiBase);
  } catch (err) {
    console.error(`[sync-catalog] ERROR: ${err.message}`);
    console.error("[sync-catalog] Build will continue with the existing catalog.js");
  }
}

/**
 * Mirror the site's filter vocabulary into vocabulary.js.
 *
 * The launcher's search used to hardcode its own TAGS list. It had drifted to
 * 37 largely invented values that matched almost nothing in the catalog and
 * shared little with the website's, so the same game looked differently
 * filterable depending on which surface you were on. The site now sends its
 * canonical lists with the catalog, and this writes them next to it.
 *
 * Refuses to write an empty list, for the same reason the catalog write does:
 * an API that answers without these fields (an older deploy, or a partial
 * response) must leave the last known-good vocabulary in place rather than
 * blank out every filter in the app.
 */
function writeVocabulary(data, apiBase) {
  const tags = Array.isArray(data.tags) ? data.tags : [];
  const features = Array.isArray(data.features) ? data.features : [];
  if (tags.length === 0 || features.length === 0) {
    console.warn(
      "[sync-catalog] API sent no tags/features — keeping the existing vocabulary.js"
    );
    return;
  }

  const vocabPath = path.join(__dirname, "..", "renderer", "vocabulary.js");
  const body = [
    "// Auto-generated by scripts/sync-catalog.js — do not edit by hand.",
    `// Synced from ${apiBase} at ${new Date().toISOString()}`,
    "//",
    "// These mirror TAGS and FEATURES in platform/src/lib/gamePayload.ts. Change",
    "// them there; the next catalog sync brings them across.",
    "",
    `export const TAGS = ${JSON.stringify(tags, null, 2)};`,
    "",
    `export const FEATURES = ${JSON.stringify(features, null, 2)};`,
    "",
  ].join("\n");
  fs.writeFileSync(vocabPath, body, "utf-8");
  console.log(
    `[sync-catalog] Wrote ${tags.length} tag(s) and ${features.length} feature(s) to renderer/vocabulary.js`
  );
}

main();
