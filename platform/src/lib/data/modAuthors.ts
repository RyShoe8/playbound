/**
 * People who make mods, as distinct from the studios who make games.
 *
 * A mod author is not a game studio and should not be described like one.
 * `Developer` carries tagline, about, founded and location because that is
 * what a studio page needs; for a modder those fields are either unknown or
 * meaningless, and filling them in would mean publishing invented facts. What
 * is actually true and checkable about a mod author is their name, where they
 * publish, and what they have made — so that is all this type holds.
 *
 * Every entry here was derived from the upstream host rather than guessed:
 * the GitHub users API, the OpenTTD BaNaNaS package API, or the author
 * segment of a Luanti / Codeberg / GitLab URL. Optional fields are omitted
 * when the host does not publish them, never filled with a placeholder.
 *
 * Mods point here through the same `developerSlug` they already use; the
 * lookup falls back to this registry when the slug is not a game studio.
 */
export interface ModAuthor {
  slug: string;
  /** Display name — the host's real name when it publishes one, else the handle. */
  name: string;
  /** Account handle on the host below. */
  handle: string;
  /** Where the attribution was verified. */
  host: "github" | "luanti" | "codeberg" | "gitlab" | "bananas" | "modio" | "moddb" | "sourceforge";
  /**
   * Profile page on that host. Optional because two credits are a team name
   * from a ModDB "Developer" field rather than an account, and inventing a
   * profile URL for them would be worse than having none.
   */
  profileUrl?: string;
  /** Personal site, when the author lists one and it is not just the profile. */
  website?: string;
  /** The author's own words. Never written by us. */
  bio?: string;
  location?: string;
}

