import { beforeEach, expect, it, vi } from "vitest";
const mocks = vi.hoisted(() => ({ update: vi.fn(), create: vi.fn(), find: vi.fn() }));
vi.mock("@/lib/db", () => ({ default: vi.fn(async () => undefined) }));
vi.mock("@/lib/models/BugReport", () => ({ default: { updateOne: mocks.update, create: mocks.create, findOne: mocks.find } }));
import { maybeUpsertAutoBugFromTelemetry } from "./autoBugReport";
const input = { event: "community_server_update_failed", properties: {
  source: "website", installationUpdateJobId: "a508e5fc-e88f-47aa-8536-549613054818", gameSlug: "team-fortress-2",
  code: "UPDATE_FAILED", phase: "installation_update", message: "EAI_AGAIN: server update could not resolve Steam",
} };
beforeEach(() => { vi.clearAllMocks(); mocks.update.mockResolvedValue({ acknowledged: true }); });
it("server-side network failures create an idempotent bug receipt without reopening dismissed reports", async () => {
  await maybeUpsertAutoBugFromTelemetry(input); await maybeUpsertAutoBugFromTelemetry(input);
  expect(mocks.update).toHaveBeenCalledTimes(2);
  expect(mocks.update.mock.calls[0][0]).toEqual(mocks.update.mock.calls[1][0]);
  expect(mocks.update.mock.calls[0][0]._id).toMatch(/^[a-f0-9]{24}$/);
  expect(mocks.update.mock.calls[0][1]).toEqual({ $setOnInsert: expect.objectContaining({ autoGenerated: true, status: "open", occurrenceCount: 1, gameSlug: "team-fortress-2" }) });
  expect(mocks.find).not.toHaveBeenCalled(); expect(mocks.create).not.toHaveBeenCalled();
});
it("bug write failures propagate so the VPS keeps the outbox entry", async () => {
  mocks.update.mockRejectedValueOnce(new Error("database unavailable"));
  await expect(maybeUpsertAutoBugFromTelemetry(input)).rejects.toThrow("database unavailable");
});
