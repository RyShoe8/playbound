#!/usr/bin/env node
// Builds docs/hosting-release-gate-matrix.md: one row per installation target with
// its update strategy, identity/isolation status, saved acceptance evidence and
// world-backup coverage. Everything except the evidence comes from the agent source.
//
//   node releaseGateMatrix.mjs evidence.json ../../docs/hosting-release-gate-matrix.md
//
// evidence.json is {"<game>": "accepted" | "blocked"}, built from the files in
// /var/lib/playbound-host/state/native-identity-acceptance on the VPS (a file whose
// `status` is "blocked" is a recorded blocker, not acceptance).
import fs from "node:fs";
import { fileURLToPath, pathToFileURL } from "node:url";
import path from "node:path";

const here = path.dirname(fileURLToPath(import.meta.url));
const load = (name) => import(pathToFileURL(path.join(here, name)).href);
const { INSTALLATION_TARGETS, installationKey } = await load("installationTargets.js");
const { hostingReadiness } = await load("hostingReadiness.js");
const { CUSTOMER_IDENTITY_GAMES } = await load("customerIdentityProfiles.js");
const { automaticInstallationUpdate } = await load("dailyInstallationUpdates.js");
const manual = JSON.parse(fs.readFileSync(path.join(here, "manualInstallationUpdates.json"), "utf8"));
const evidence = JSON.parse(fs.readFileSync(process.argv[2], "utf8"));
const out = process.argv[3];
if (!out) throw new Error("usage: releaseGateMatrix.mjs evidence.json output.md");

const block = fs.readFileSync(path.join(here, "dedicatedDataBackups.js"), "utf8").match(/const WORLD_SOURCES = \{([\s\S]*?)\n\};/)?.[1] ?? "";
const worlds = new Set([...block.matchAll(/^\s{2}"?([a-z0-9-]+)"?:/gm)].map((m) => m[1]));
const gameFor = new Map(CUSTOMER_IDENTITY_GAMES.map((g) => [installationKey(g), g]));

const rows = Object.keys(INSTALLATION_TARGETS).sort().map((key) => {
  let r;
  try { r = hostingReadiness(key); } catch (e) { r = { isolation: "error", reason: String(e.message) }; }
  const game = gameFor.get(key) || key;
  const state = evidence[game] ?? evidence[key];
  return {
    key,
    name: INSTALLATION_TARGETS[key].name,
    updates: automaticInstallationUpdate(key) ? "automatic" : manual[key] ? "manual (declared)" : "UNDECLARED",
    identity: gameFor.has(key) ? "implemented" : "none",
    isolation: r.isolation,
    evidence: state === "accepted" ? "accepted" : state === "blocked" ? "recorded blocker" : "none",
    backups: worlds.has(game) || worlds.has(key) ? "yes" : "no",
    reason: String(r.reason || "").replace(/\s+/g, " ").replace(/\|/g, "/"),
  };
});

const count = (f) => rows.reduce((a, r) => ((a[r[f]] = (a[r[f]] || 0) + 1), a), {});
const fmt = (o) => Object.entries(o).map(([k, v]) => `${k} ${v}`).join(", ");
const open = rows.filter((r) => r.isolation !== "operator_rollout" || r.evidence !== "accepted");
const md = [
  "# Dedicated hosting release gate matrix",
  "",
  "Generated by `platform/game-host/releaseGateMatrix.mjs` from the agent source plus the acceptance",
  "files on the VPS. The release gate (plan step 7) needs every row to have saved acceptance",
  "evidence or an explicit surfaced limitation; this table shows which do. Regenerate it after",
  "each acceptance instead of editing it by hand.",
  "",
  `Targets: ${rows.length}. Isolation: ${fmt(count("isolation"))}. Updates: ${fmt(count("updates"))}.`,
  `Acceptance evidence: ${fmt(count("evidence"))}. World backups: ${fmt(count("backups"))}.`,
  "",
  "`operator_rollout` means the identity handoff is implemented and accepted but each server still needs",
  "explicit offline enrollment; it is not customer-wide isolation. `blocked` and `pending` rows surface",
  "their specific missing boundary in the admin hosting readiness view (the reason column).",
  "",
  "| Installation | Updates | Identity | Isolation | Evidence | Backups | Surfaced limitation |",
  "| --- | --- | --- | --- | --- | --- | --- |",
  ...rows.map((r) => `| ${r.name} (\`${r.key}\`) | ${r.updates} | ${r.identity} | ${r.isolation} | ${r.evidence} | ${r.backups} | ${r.reason.slice(0, 220)}${r.reason.length > 220 ? "…" : ""} |`),
  "",
  `## Still open (${open.length})`,
  "",
  ...open.map((r) => `- **${r.name}** — ${r.isolation}, evidence: ${r.evidence}`),
  "",
].join("\n");
fs.writeFileSync(out, md);
console.log(JSON.stringify({ rows: rows.length, open: open.length, isolation: count("isolation"), evidence: count("evidence") }));
